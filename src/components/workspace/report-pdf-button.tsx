'use client';

import { useCallback, useState } from 'react';
import { Button } from '@/components/ui/button';

export type PlainReportItem = string | { text: string; details?: string[] };

export type PlainReportSection = {
  heading: string;
  /** Short paragraphs or list entries; objects carry indented detail lines. */
  lines: PlainReportItem[];
  /** Render lines as a numbered list instead of plain paragraphs. */
  numbered?: boolean;
};

export type PlainReport = {
  title: string;
  subtitle?: string;
  sections: PlainReportSection[];
};

/**
 * Builds a text-only PDF (vector text, built-in font, no images), so files stay
 * in the tens of KB instead of the tens of MB a page screenshot produces.
 */
export function ReportPdfButton({
  report,
  filename = 'audit-report.pdf',
}: {
  report: PlainReport;
  filename?: string;
}) {
  const [generating, setGenerating] = useState(false);

  const handleDownload = useCallback(async () => {
    setGenerating(true);
    try {
      const { jsPDF } = await import('jspdf');
      const pdf = new jsPDF({ unit: 'mm', format: 'a4', compress: true });

      const margin = 18;
      const pageWidth = pdf.internal.pageSize.getWidth();
      const pageHeight = pdf.internal.pageSize.getHeight();
      const textWidth = pageWidth - margin * 2;
      let y = margin;

      // Built-in PDF fonts are Latin-1 only; swap common symbols so text extracts cleanly.
      const clean = (t: string) =>
        t
          .replace(/[\u2018\u2019]/g, "'")
          .replace(/[\u201C\u201D]/g, '"')
          .replace(/[\u2013\u2014]/g, '-')
          .replace(/\u2026/g, '...')
          .replace(/[^\x09\x0A\x20-\x7E\xA0-\xFF]/g, '');

      const write = (
        text: string,
        opts: { size: number; bold?: boolean; gray?: boolean; indent?: number; gap?: number },
      ) => {
        const indent = opts.indent ?? 0;
        pdf.setFont('helvetica', opts.bold ? 'bold' : 'normal');
        pdf.setFontSize(opts.size);
        pdf.setTextColor(opts.gray ? 90 : 20);
        const lineHeight = opts.size * 0.5;
        const wrapped = pdf.splitTextToSize(clean(text), textWidth - indent) as string[];
        for (const line of wrapped) {
          if (y + lineHeight > pageHeight - margin) {
            pdf.addPage();
            y = margin;
          }
          pdf.text(line, margin + indent, y + lineHeight * 0.8);
          y += lineHeight;
        }
        y += opts.gap ?? 0;
      };

      write(report.title, { size: 20, bold: true, gap: 1 });
      if (report.subtitle) write(report.subtitle, { size: 11, gray: true, gap: 4 });

      for (const section of report.sections) {
        if (section.lines.length === 0) continue;
        y += 4;
        write(section.heading, { size: 13, bold: true, gap: 2 });
        section.lines.forEach((line, i) => {
          const item = typeof line === 'string' ? { text: line, details: [] } : line;
          const details = item.details ?? [];
          write(section.numbered ? `${i + 1}. ${item.text}` : item.text, {
            size: 10.5,
            bold: details.length > 0,
            gap: details.length > 0 ? 0.5 : 2,
          });
          details.forEach((d, j) =>
            write(d, { size: 10, indent: 5, gap: j === details.length - 1 ? 3 : 0.5 }),
          );
        });
      }

      // Watermark: footer on every page, below the content area.
      const pages = pdf.getNumberOfPages();
      for (let page = 1; page <= pages; page++) {
        pdf.setPage(page);
        pdf.setFont('helvetica', 'normal');
        pdf.setFontSize(8);
        pdf.setTextColor(130);
        pdf.text('Brief generated by Site-OS', margin, pageHeight - 9);
        pdf.text(`Page ${page} of ${pages}`, pageWidth - margin, pageHeight - 9, { align: 'right' });
      }

      pdf.setProperties({ title: report.title, subject: 'Website audit fix brief' });
      pdf.save(filename);
    } finally {
      setGenerating(false);
    }
  }, [report, filename]);

  return (
    <Button
      variant="outline"
      size="sm"
      onClick={handleDownload}
      disabled={generating}
      data-no-print
      className="gap-1.5"
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width="14"
        height="14"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4" />
        <polyline points="7 10 12 15 17 10" />
        <line x1="12" y1="15" x2="12" y2="3" />
      </svg>
      {generating ? 'Generating…' : 'Download PDF'}
    </Button>
  );
}
